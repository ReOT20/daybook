#!/usr/bin/env python3
"""Validate keyed UTF-8 catalogs and generate shared Kotlin, including CLDR integer plurals."""
import argparse
import json
import re
from pathlib import Path

from babel import Locale

ROOT = Path(__file__).resolve().parents[2]
CATALOGS = ROOT / 'translations'
OUT = ROOT / 'app/src/main/java/com/joebywan/daybook/core/i18n/generated'
LOCALE_CONFIG = ROOT / 'app/src/main/res/xml/locale_config.xml'
PLACEHOLDER = re.compile(r'\{([A-Za-z][A-Za-z0-9_]*)\}')
CATEGORIES = {'zero', 'one', 'two', 'few', 'many', 'other'}
HEADER = '// Generated by tools/i18n/build.py; edit translations/, then regenerate.\npackage com.joebywan.daybook.core.i18n\n\n'


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f'duplicate JSON key: {key}')
        result[key] = value
    return result


def load(path):
    return json.loads(path.read_text(), object_pairs_hook=unique_object)


def kotlin(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')


def forms(value):
    if isinstance(value, str):
        return {'other': value}
    if not isinstance(value, dict) or 'other' not in value or set(value) - CATEGORIES:
        raise ValueError('message must be a string or plural forms including other')
    if not all(isinstance(text, str) for text in value.values()):
        raise ValueError('plural forms must contain strings')
    return value


def plural_expr(node):
    """Babel's pinned CLDR AST; counts are integers, so decimal/exponent operands are zero."""
    operator, args = node
    if operator in ('n', 'i'):
        return 'n'
    if operator in ('v', 'w', 'f', 't', 'c', 'e'):
        return '0uL'
    if operator == 'value':
        return f'{args[0]}uL'
    if operator == 'mod':
        return f'({plural_expr(args[0])} % {plural_expr(args[1])})'
    if operator in ('and', 'or'):
        join = ' && ' if operator == 'and' else ' || '
        return '(' + join.join(plural_expr(arg) for arg in args) + ')'
    if operator == 'not':
        return f'!({plural_expr(args[0])})'
    if operator == 'relation':
        relation, operand, ranges = args
        if relation not in ('in', 'within') or ranges[0] != 'range_list':
            raise ValueError(f'unsupported CLDR relation: {node}')
        expr = plural_expr(operand)
        tests = []
        for low, high in ranges[1]:
            a, b = plural_expr(low), plural_expr(high)
            tests.append(f'{expr} == {a}' if a == b else f'{expr} in {a}..{b}')
        return '(' + ' || '.join(tests) + ')'
    raise ValueError(f'unsupported CLDR AST node: {node}')


def calendar_metadata(tags):
    output = HEADER + '/** Gregorian calendar names from Babel 2.17 / Unicode CLDR; weekdays are Monday first. */\n'
    output += 'internal val catalogCalendars: Map<String, CalendarNames> = mapOf(\n'
    for tag in tags:
        locale = Locale.parse(tag.replace('-', '_'))
        weekdays = locale.days['format']
        months = locale.months
        # English's single letters are established UI; other languages use CLDR's short standalone labels.
        captions = locale.days['stand-alone']['narrow' if tag == 'en' else 'short']
        values = {
            'weekdays': [weekdays['wide'][day] for day in range(7)],
            'shortWeekdays': [weekdays['abbreviated'][day] for day in range(7)],
            'weekdayCaptions': [captions[day].title() for day in range(7)],
            'months': [months['format']['wide'][month] for month in range(1, 13)],
            'standaloneMonths': [months['stand-alone']['wide'][month] for month in range(1, 13)],
            'shortMonths': [months['format']['abbreviated'][month] for month in range(1, 13)],
        }
        output += f'    {kotlin(tag)} to CalendarNames(\n'
        for name, names in values.items():
            output += f'        {name} = listOf(' + ', '.join(kotlin(value) for value in names) + '),\n'
        output += '    ),\n'
    return output + ')\n'


def generate(catalog_dir=CATALOGS):
    languages = load(catalog_dir / 'languages.json')
    tags = [language['tag'] for language in languages]
    if not tags or tags[0] != 'en' or len(set(tags)) != len(tags):
        raise ValueError('languages must begin with en and contain unique tags')
    for language in languages:
        if not re.fullmatch(r'[a-z]{2,3}(?:-[A-Za-z0-9]+)*', language['tag']) or not language['nativeName']:
            raise ValueError(f'invalid language metadata: {language}')
    catalogs = {}
    for tag in tags:
        messages = {}
        for path in sorted((catalog_dir / tag).glob('*.json')):
            for key, value in load(path).items():
                if key in messages:
                    raise ValueError(f'{path}: duplicate message {key}')
                if not re.fullmatch(r'[a-z][a-z0-9_.-]*', key):
                    raise ValueError(f'{path}: invalid message key {key}')
                messages[key] = forms(value)
        catalogs[tag] = messages
    english = catalogs['en']
    if not english:
        raise ValueError('English catalog is empty')
    for tag, messages in catalogs.items():
        missing, extra = english.keys() - messages.keys(), messages.keys() - english.keys()
        if missing or extra:
            raise ValueError(f'{tag}: missing {sorted(missing)}, extra {sorted(extra)}')
        rule = Locale.parse(tag.replace('-', '_')).plural_form
        for key, variants in messages.items():
            reference = set().union(*(set(PLACEHOLDER.findall(text)) for text in english[key].values()))
            found = set().union(*(set(PLACEHOLDER.findall(text)) for text in variants.values()))
            if found != reference:
                raise ValueError(f'{tag}:{key}: placeholders {sorted(found)} differ from English {sorted(reference)}')
            if len(english[key]) > 1 and not (rule.tags | {'other'}) <= variants.keys():
                raise ValueError(f'{tag}:{key}: missing CLDR forms {sorted((rule.tags | {"other"}) - variants.keys())}')
            for value in variants.values():
                if reference - {'count'} - set(PLACEHOLDER.findall(value)):
                    raise ValueError(f'{tag}:{key}: a form drops a message argument')
    result = {}
    registry = HEADER + 'internal val catalogLanguages = listOf(\n'
    registry += ''.join(f'    Language({kotlin(lang["tag"])}, {kotlin(lang["nativeName"])}),\n' for lang in languages)
    registry += ')\n\ninternal val catalogEntries: Map<String, Map<String, CatalogEntry>> = mapOf(\n'
    for tag, messages in catalogs.items():
        parts = []
        items = sorted(messages.items())
        identifier = tag.replace('-', '_')
        for offset in range(0, len(items), 100):
            function = f'catalog_{identifier}_{offset // 100}'
            parts.append(function + '()')
            output = HEADER + f'internal fun {function}(): Map<String, CatalogEntry> = mapOf(\n'
            for key, variants in items[offset:offset + 100]:
                body = ', '.join(f'{kotlin(category)} to {kotlin(text)}' for category, text in variants.items())
                output += f'    {kotlin(key)} to CatalogEntry(mapOf({body})),\n'
            result[f'{function}.kt'] = output + ')\n'
        registry += f'    {kotlin(tag)} to (' + ' + '.join(parts) + '),\n'
    result['Catalogs.kt'] = registry + ')\n'
    plural = HEADER + '/** Cardinal integer rules generated from Babel 2.17 / Unicode CLDR. */\n'
    plural += 'internal fun catalogPlural(language: String, count: Long): String {\n'
    plural += '    val n = if (count < 0) (-(count + 1)).toULong() + 1uL else count.toULong()\n'
    plural += '    return when (language) {\n'
    for tag in tags:
        plural += f'        {kotlin(tag)} -> when {{\n'
        for category, tree in Locale.parse(tag.replace('-', '_')).plural_form.abstract:
            plural += f'            {plural_expr(tree)} -> {kotlin(category)}\n'
        plural += '            else -> "other"\n        }\n'
    result['PluralRules.kt'] = plural + '        else -> "other"\n    }\n}\n'
    result['CalendarNames.kt'] = calendar_metadata(tags)
    return result, len(english), tags


def validate_references(paths, keys):
    calls = re.compile(r'\b(?:text|message|savedText|SavedText)\(\s*"([^"\n]+)"')
    for path in paths:
        source = path.read_text()
        if re.search(r'\btr\(', source):
            raise ValueError(f'{path}: inline bilingual tr() is retired; use catalog keys')
        for match in calls.finditer(source):
            key = match[1]
            prefix = key.split('$', 1)[0]
            valid = key in keys if '$' not in key else any(k.startswith(prefix) for k in keys)
            if not valid:
                line = source.count('\n', 0, match.start()) + 1
                raise ValueError(f'{path}:{line}: unknown translation key {key}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if committed generated files differ')
    args = parser.parse_args()
    generated, count, tags = generate()
    english_keys = {key for path in (CATALOGS / 'en').glob('*.json') for key in load(path)}
    sources = [path for directory in ('app/src/main/java', 'web/src/wasmJsMain/kotlin')
               for path in (ROOT / directory).rglob('*.kt') if 'generated' not in path.parts]
    validate_references(sources, english_keys)
    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, content in generated.items():
        target = OUT / name
        if not target.exists() or target.read_text() != content:
            stale.append(name)
            if not args.check:
                target.write_text(content)
    extra = {path.name for path in OUT.glob('*.kt')} - generated.keys()
    stale.extend(sorted(extra))
    locales = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/i18n/build.py from translations/languages.json. -->\n'
    locales += '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n'
    locales += ''.join(f'    <locale android:name="{tag}" />\n' for tag in tags)
    locales += '</locale-config>\n'
    if not LOCALE_CONFIG.exists() or LOCALE_CONFIG.read_text() != locales:
        stale.append(str(LOCALE_CONFIG.relative_to(ROOT)))
        if not args.check:
            LOCALE_CONFIG.write_text(locales)
    if not args.check:
        for name in extra:
            (OUT / name).unlink()
    if args.check and stale:
        parser.exit(1, 'Stale generated catalogs; run tools/i18n/build.py: ' + ', '.join(stale) + '\n')
    print(f'{count} message keys, languages: {", ".join(tags)}; catalogs {"checked" if args.check else "generated"}')


if __name__ == '__main__':
    main()
