package com.joebywan.daybook

import com.joebywan.daybook.core.Difficulty
import com.joebywan.daybook.core.Rng
import com.joebywan.daybook.core.Verdict
import com.joebywan.daybook.core.words.RussianWords
import com.joebywan.daybook.puzzles.CipherLogic
import com.joebywan.daybook.puzzles.CipherSum
import com.joebywan.daybook.puzzles.CipherTeacher
import com.joebywan.daybook.puzzles.CodewordLogic
import com.joebywan.daybook.puzzles.CodewordTeacher
import com.joebywan.daybook.puzzles.CodewordWords
import com.joebywan.daybook.puzzles.MiniLogic
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File
import java.util.concurrent.Executors
import java.util.concurrent.atomic.AtomicIntegerArray

/** Opt-in offline build, using the existing filler and proof gates with the frozen Russian lists. */
class RussianWordPuzzlesBuildTest {
    @Test fun build() {
        val selected = System.getenv("DAYBOOK_RUSSIAN_BUILD")
        assumeTrue("set DAYBOOK_RUSSIAN_BUILD=mini, codeword or cipher", selected != null)
        val family = requireNotNull(selected)
        require(family in listOf("mini", "codeword", "cipher"))
        val out = requireNotNull(System.getenv("DAYBOOK_RUSSIAN_OUTPUT"))
        val want = System.getenv("DAYBOOK_RUSSIAN_PER_TIER")?.toInt() ?: 1000
        require(want > 0)
        val pool = Executors.newFixedThreadPool(12)
        try {
            val tiers = if (family == "cipher") sums(pool, want) else Difficulty.entries.associateWith { tier ->
                val failures = AtomicIntegerArray(5)
                CrosswordFill.buildTier(tier, pool, want, 400_000, 240, failures, stall = 40,
                    key = { it.substringBefore(':') }, stats = { found, drawn ->
                        println("Russian $family $tier: ${found.size} from $drawn draws")
                    },
                ) { i -> grid(family, tier, Rng(20261106L * 1_000_003L + tier.ordinal * 10_000_019L + i), failures,
                    blockVariant = i / 240 % (if (tier == Difficulty.STANDARD) 2 else 3)) }
            }
            require(tiers.values.all { it.size >= minOf(want, 365) }) { "Fewer than 365 proved Russian $family entries (or the requested smaller probe): ${tiers.mapValues { it.value.size }}" }
            val name = when (family) { "mini" -> "RussianMiniGrids"; "codeword" -> "RussianCodewordGrids"; else -> "RussianCipherSums" }
            val source = CrosswordFill.source(name, listOf(
                "GENERATED by RussianWordPuzzlesBuildTest from the frozen RussianWords corpus; see tools/words/ru/README.md.",
                "Sorted list indices are board identity. Do not reorder or regenerate after release without a versioned content set.",
            ), tiers, 100).replace("internal object $name {", "internal object $name {\n    fun entries(difficulty: com.joebywan.daybook.core.Difficulty): List<String> = when (difficulty) {\n" +
                Difficulty.entries.joinToString("\n") { "        com.joebywan.daybook.core.Difficulty.${it.name} -> ${it.name}" } + "\n    }\n")
            File(out).writeText(source)
        } finally { pool.shutdownNow() }
    }

    private val indexes by lazy { (3..7).associateWith { CrosswordFill.Index(RussianWords.grid(it), RussianWords.ALPHABET) } }
    private val wide by lazy { (3..7).associateWith { CodewordWords.Length(RussianWords.guesses(it), "ru") } }

    private fun grid(family: String, tier: Difficulty, rng: Rng, failures: AtomicIntegerArray, blockVariant: Int = 0): String? {
        val mini = family == "mini"
        val size = if (mini) MiniLogic.specFor(tier).size else CodewordLogic.specFor(tier).size
        // Native block layouts broaden the Russian fills; uniqueness, clue-share and teaching gates are unchanged.
        val shape = if (mini) MiniGridsBuildTest.SHAPES.getValue(tier).let { CrosswordFill.Shape(it.maxRun, it.blacks + 2 * blockVariant) }
            else if (tier == Difficulty.EXPERT) CrosswordFill.Shape(6, 52)
            else CodewordGridsBuildTest.SHAPES.getValue(tier)
        val white = CrosswordFill.pattern(rng, size, 3, shape.maxRun, shape.blacks) ?: return null.also { failures.incrementAndGet(0) }
        val grid = CrosswordFill.fill(rng, white, size, indexes, 20_000) ?: return null.also { failures.incrementAndGet(1) }
        val squares = grid.concatToString()
        if (mini) return squares.takeIf { MiniLogic.board(it, tier, "ru") != null }.also { if (it == null) failures.incrementAndGet(2) }
        val alphabet = squares.filter { it != '#' }.map { RussianWords.ALPHABET.indexOf(it) }.distinct().sorted()
        val numbers = squares.map { if (it == '#') 0 else alphabet.indexOf(RussianWords.ALPHABET.indexOf(it)) + 1 }
        val upTo = CodewordTeacher.TECHNIQUES.indexOf(CodewordLogic.specFor(tier).needs)
        val givens = alphabet.toMutableSet()
        fun known() = alphabet.map { if (it in givens) it else CodewordLogic.EMPTY }
        for (l in rng.shuffled(alphabet)) {
            if (givens.size == 1) break
            givens -= l
            if (CodewordTeacher.walk(size, numbers, known(), upTo, "ru") == null) givens += l
        }
        val letters = known()
        val walk = CodewordTeacher.walk(size, numbers, letters, upTo, "ru") ?: return null.also { failures.incrementAndGet(2) }
        if (givens.size == alphabet.size || (tier != Difficulty.STANDARD && walk.none { it.technique == CodewordLogic.specFor(tier).needs })) return null.also { failures.incrementAndGet(2) }
        if (CodewordLogic.solve(size, numbers, letters, "ru") !is Verdict.ExactlyOne) return null.also { failures.incrementAndGet(3) }
        if (CodewordLogic.solve(size, numbers, letters, "ru") { wide.getValue(it) } !is Verdict.ExactlyOne) return null.also { failures.incrementAndGet(4) }
        return "$squares:" + givens.sorted().map { RussianWords.ALPHABET[it] }.joinToString("")
    }

    private fun sums(pool: java.util.concurrent.ExecutorService, want: Int): Map<Difficulty, List<String>> {
        val fours = RussianWords.answers(4)
        val fives = RussianWords.answers(5)
        val rng = Rng(20261106L)
        val seen = HashSet<String>()
        val tiers = Difficulty.entries.associateWith { mutableListOf<String>() }
        val pairs = fours.size * (fours.size - 1) / 2
        var drawn = 0
        while (tiers.values.any { it.size < want } && seen.size < pairs) {
            val batch = mutableListOf<Pair<String, String>>()
            while (batch.size < 240 && seen.size < pairs) {
                val a = rng.pick(fours); val b = rng.pick(fours)
                if (a == b || !seen.add(minOf(a, b) + maxOf(a, b))) continue
                batch += a to b
            }
            val open = tiers.mapValues { (_, list) -> if (list.size >= want) null else list.groupingBy { it.substringAfter('=') }.eachCount() }
            val found = batch.map { (a, b) -> pool.submit<Pair<String, Difficulty>?> {
                fives.firstNotNullOfOrNull { total ->
                    val sum = CipherSum(listOf(a, b, total), "ru")
                    if (!sum.wellFormed || CipherLogic.prove(sum) !is Verdict.ExactlyOne || !CipherTeacher.solvesByLogic(sum)) return@firstNotNullOfOrNull null
                    val tier = CipherSumsBuildTest.tierOf(sum)
                    val counts = open.getValue(tier) ?: return@firstNotNullOfOrNull null
                    if ((counts[total] ?: 0) >= 3) null else "$a+$b=$total" to tier
                }
            } }.mapNotNull { it.get() }
            for ((entry, tier) in found) tiers.getValue(tier).let { list ->
                if (list.size < want && list.count { it.endsWith("=${entry.substringAfter('=')}") } < 3) list += entry
            }
            drawn += batch.size
            println("Russian cipher drawn $drawn: ${tiers.mapValues { it.value.size }}")
        }
        return tiers.mapValues { it.value.sorted() }
    }
}
